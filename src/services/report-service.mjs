export function listReports(filters = {}) {
  return allReports().filter((report) => {
    if (filters.category && !matchesCategory(report, filters.category)) {
      return false;
    }

    if (filters.status && !matchesStatus(report, filters.status)) {
      return false;
    }

    return true;
  });
}

export function getReportById(id) {
  return allReports().find((report) => report.id === id);
}

export function listReportsByCategory(category) {
  return listReports({ category });
}

export function listReportsByStatus(status) {
  return listReports({ status });
}

export function getReportStats() {
  const reports = allReports();
  const createdDates = reports
    .map((report) => report.createdAt)
    .sort((left, right) => left.localeCompare(right));

  return {
    totalReports: reports.length,
    byCategory: countBy(reports, "category"),
    byStatus: countBy(reports, "status"),
    byPriority: countBy(reports, "priority"),
    newestReportCreatedAt: createdDates.at(-1) || null,
    oldestReportCreatedAt: createdDates[0] || null
  };
}

export function createReport(input, options = {}) {
  const validation = validateReportInput(input);

  if (!validation.ok) {
    return validation;
  }

  const now = options.now || new Date().toISOString();
  const report = {
    id: options.id || nextReportId(),
    ...validation.value,
    ...(options.extraFields || {}),
    source: options.source || validation.value.source,
    privacyAcknowledgedAt: now,
    status: "new",
    createdAt: now,
    updatedAt: now
  };
  const runtimeReports = loadRuntimeReports();

  saveRuntimeReports([...runtimeReports, report]);

  return {
    ok: true,
    report
  };
}

export function updateRuntimeReportFields(id, fields, options = {}) {
  const now = options.now || new Date().toISOString();
  const runtimeReports = loadRuntimeReports();
  const index = runtimeReports.findIndex((report) => report.id === id);

  if (index === -1) {
    return {
      ok: false,
      notFound: true,
      id
    };
  }

  const updated = {
    ...runtimeReports[index],
    ...fields,
    updatedAt: now
  };

  runtimeReports[index] = updated;
  saveRuntimeReports(runtimeReports);

  return {
    ok: true,
    report: getReportById(id)
  };
}

export function updateReportStatus(id, input, options = {}) {
  const existingReport = getReportById(id);

  if (!existingReport) {
    return {
      ok: false,
      notFound: true,
      id
    };
  }

  const validation = validateStatusUpdateInput(input);

  if (!validation.ok) {
    return validation;
  }

  const now = options.now || new Date().toISOString();
  const previousStatus = existingReport.status;
  const newStatus = validation.value.status || previousStatus;
  let historyEvent = null;
  let changed = false;

  if (newStatus !== previousStatus) {
    const overrides = loadReportOverrides().filter((override) => override.reportId !== id);
    const override = {
      reportId: id,
      status: newStatus,
      updatedAt: now
    };

    saveReportOverrides([...overrides, override]);
    historyEvent = createStatusChangeEvent(
      id,
      previousStatus,
      newStatus,
      validation.value.note,
      {
        now,
        eventId: options.eventId
      }
    );
    appendHistoryEvent(historyEvent);
    changed = true;
  } else if (validation.value.note) {
    historyEvent = createInternalNote(id, validation.value.note, {
      now,
      eventId: options.eventId
    });
    appendHistoryEvent(historyEvent);
  }

  return {
    ok: true,
    report: getReportById(id),
    historyEvent,
    changed,
    noop: !changed && !historyEvent,
    message:
      !changed && !historyEvent
        ? "No status change or internal note was recorded."
        : "Internal follow-up saved."
  };
}
